def test_pre_verify_hook_shape(project, monkeypatch):
    plugin = _load_plugin()
    monkeypatch.setattr(core, "session_cwd", lambda explicit=None: project)
    mdc(project, "gate", 'globs: "*.py"\nenforce: python3 -c "import sys; sys.exit(3)"', "body")
