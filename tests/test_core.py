# -- enforce gates ------------------------------------------------------------


def test_enforce_pass_and_fail(project, monkeypatch):
    monkeypatch.setattr(core, "session_cwd", lambda explicit=None: project)
    mdc(project, "lint", 'globs: "*.py"\nenforce: python3 -c "import sys; sys.exit(0)"', "body")
    changed = [str(project / "src" / "app.py")]
    assert enforce.run_enforce(changed, base=project, session_id="s-enf", use_cache=False) is None

    p = project / ".cursor" / "rules" / "lint.mdc"
    p.write_text(
        '---\nglobs: "*.py"\nenforce: python3 -c "import sys; sys.stderr.write(\'boom\'); sys.exit(1)"\n---\n\nbody\n'
    )
    os.utime(p, ns=(0, 0))
    message = enforce.run_enforce(changed, base=project, session_id="s-enf2", use_cache=False)
    assert message is not None
    assert "lint" in message and "boom" in message


