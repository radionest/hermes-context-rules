def test_cache_invalidates_on_mtime(project):
    p = mdc(project, "r1", "globs: **/*.py", "one")
    (r1,) = core.load_rules(project)
    assert r1.body == "one"
    os.utime(p, ns=(0, 0))
    p.write_text("---\nglobs: **/*.py\n---\n\ntwo\n")
    (r2,) = core.load_rules(project)
    assert r2.body == "two"


# -- glob matching -----------------------------------------------------------


@pytest.mark.parametrize(
    "pattern,path,expected",
    [
        ("src/**/*.py", "src/app.py", True),
        ("src/**/*.py", "src/a/b/c.py", True),
        ("src/*.py", "src/a/b/c.py", False),
        ("*.py", "src/app.py", True),          # bare pattern matches basename anywhere
        ("*.md", "README.md", True),
        ("**/*.md", "docs/deep/nested.md", True),
        ("src/**", "src/a/b/c.py", True),
    ],
)
def test_glob_matching(project, pattern, path, expected):
    mdc(project, "g", f"globs: {pattern}", "body")
    (rule,) = core.load_rules(project)
    target = project / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("")
    assert core.rule_matches_path(rule, str(target), base=project) is expected


def test_rules_for_paths_dedupes(project):
    mdc(project, "py", "globs: src/**/*.py", "py rules")
    mdc(project, "all", "globs: **/*", "all rules")
    matched = core.rules_for_paths([str(project / "src" / "app.py")], base=project)
    assert {r.name for r in matched} == {"py", "all"}


