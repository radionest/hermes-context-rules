def test_register_uses_documented_surfaces():
    plugin = _load_plugin()
    registered = {"middleware": [], "hooks": [], "sections": [], "commands": []}

    class Ctx:
        def register_middleware(self, kind, cb):
            registered["middleware"].append(kind)

        def register_hook(self, name, cb):
            registered["hooks"].append(name)

        def register_system_prompt_section(self, sid, content, position="after_memory"):
            registered["sections"].append((sid, position))

        def register_command(self, name, handler=None, description=""):
            registered["commands"].append(name)

    plugin.register(Ctx())
    assert registered["middleware"] == ["tool_execution"]
    assert set(registered["hooks"]) == {"post_tool_call", "pre_verify"}
    assert registered["sections"] == [("context.rules.manifest", "after_memory")]
    assert registered["commands"] == ["context-rules"]
