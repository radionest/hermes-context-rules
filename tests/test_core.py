"""Standalone tests for context-rules (no Hermes imports required).

The plugin loads as a flat package (root __init__.py + sibling modules), the
same shape the Hermes loader imports; tests replicate that with importlib.
"""

from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent

# Mirror the real loader: the plugin dir is imported as a package, never put on
# sys.path. Keep the scrub so flat-import regressions cannot be masked here.
sys.path[:] = [p for p in sys.path if Path(p or ".").resolve() != REPO.resolve()]


def _load_plugin():
    """Import the plugin package exactly once, under a stable name."""
    name = "context_rules_plugin"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(
        name, REPO / "__init__.py", submodule_search_locations=[str(REPO)])
    module = importlib.util.module_from_spec(spec)
    module.__package__ = name
    module.__path__ = [str(REPO)]
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


_plugin = _load_plugin()
core = _plugin.core
enforce = _plugin.enforce
sync_rules = _plugin.sync_rules


@pytest.fixture()
def project(tmp_path: Path) -> Path:
    (tmp_path / ".git").mkdir()
    (tmp_path / "src").mkdir()
    (tmp_path / ".cursor" / "rules").mkdir(parents=True)
    (tmp_path / ".claude" / "rules").mkdir(parents=True)
    (tmp_path / "src" / "app.py").write_text("x = 1\n")
    (tmp_path / "README.md").write_text("readme\n")
    return tmp_path


def mdc(tmp_path: Path, name: str, front: str, body: str) -> Path:
    p = tmp_path / ".cursor" / "rules" / f"{name}.mdc"
    p.write_text(f"---\n{front}\n---\n\n{body}\n")
    return p


# -- discovery / parsing ----------------------------------------------------


def test_fallback_yaml_booleans_match_pyyaml():
    """Fallback parser must coerce the same YAML 1.1 booleans as PyYAML.

    Mode resolution (``alwaysApply: yes``) may not depend on whether PyYAML
    happens to be installed — the plugin's runtime often has only the fallback.
    """
    for spell in ("yes", "Yes", "YES", "on", "On", "ON", "true", "True", "TRUE"):
        assert core._fallback_yaml(f"k: {spell}") == {"k": True}, spell
    for spell in ("no", "No", "NO", "off", "Off", "OFF", "false", "False", "FALSE"):
        assert core._fallback_yaml(f"k: {spell}") == {"k": False}, spell
    # single letters stayed strings in PyYAML >= 5.1 — the fallback must agree
    assert core._fallback_yaml("k: y") == {"k": "y"}
    assert core._fallback_yaml("k: N") == {"k": "N"}


def test_finds_rules_and_modes(project):
    mdc(project, "py-style", "globs: src/**/*.py\nalwaysApply: false", "Use 4-space indent.")
    mdc(project, "always-house", "alwaysApply: true", "Be terse.")
    mdc(project, "on-demand", "description: DB migration guardrails", "Always add rollback.")
    mdc(project, "manual-thing", "alwaysApply: false", "Only when asked.")
    rules = core.load_rules(project)
    modes = {r.name: r.mode for r in rules}
    assert modes == {
        "py-style": "glob",
        "always-house": "always",
        "on-demand": "desc",
        "manual-thing": "manual",
    }


