def test_frontmatter_quoting_roundtrips_without_pyyaml(tmp_path):
    project = make_project(tmp_path)
    tricky = 'He said "stop" café #note'
    claude_md(project, "db", "Body.\n")
    sync_from_claude.apply(project, "db", "desc", tricky)
    text = (project / ".cursor" / "rules" / "db.mdc").read_text(encoding="utf-8-sig")
    # parse the written canon with the FALLBACK parser (PyYAML absent)
    saved_yaml = core.yaml
    core.yaml = None
    try:
        meta, _ = core._parse_frontmatter(text)
        assert meta.get("description") == tricky
        meta2, _ = core._parse_frontmatter("---\nglobs: [\"src/{a,b}/*.py\", \"plain.py\"]\n---\nbody")
        assert meta2.get("globs") == ["src/{a,b}/*.py", "plain.py"]
    finally:
        core.yaml = saved_yaml


