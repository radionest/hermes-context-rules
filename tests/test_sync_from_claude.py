def test_apply_conflict_needs_force(tmp_path):
    project = make_project(tmp_path)
    mdc(project, "style", "globs: **/*.py", "Old canonical body.")
    claude_md(project, "style", "---\nglobs: **/*.py\n---\n\nNew imported body.\n")
    out = sync_from_claude.apply(project, "style")
    assert "conflict" in out
