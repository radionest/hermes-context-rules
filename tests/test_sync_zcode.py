def test_zcode_duplicate_prune_keeps_only_when_managed_written(tmp_path):
    """A marked pre-rename projection stays the canon's only projection when
    the managed name is occupied by a handwritten file — mirrors claude."""
    project = make_project(tmp_path)
    mdc(project, "style", 'globs: ["**/*.py"]', "Body.")
    (project / ".zcode" / "rules").mkdir(parents=True, exist_ok=True)
    (project / ".zcode" / "rules" / "python-style.md").write_text("Handwritten note.\n")
    # a stale marked projection referencing a RENAMED-AWAY canon (style.mdc
    # no longer exists; python-style.mdc does): its ref parses, canon gone,
    # BUT the managed name is handwritten-occupied and was never written,
    # so this projection is the canon's only projection and must be kept
    (project / ".zcode" / "rules" / "style.md").write_text(
        "<!-- generated by hermes context-rules from .cursor/rules/style.mdc — do not edit here; edit the .mdc. -->\n\nBody.\n")
    mdc(project, "python-style", 'globs: ["**/*.py"]', "New body.")
    out = sync_rules.sync(str(project), target="zcode")
    assert (project / ".zcode" / "rules" / "style.md").exists()  # kept: canon's only projection
    assert (project / ".zcode" / "rules" / "python-style.md").read_text() == "Handwritten note.\n"
    assert "skipped" in out
