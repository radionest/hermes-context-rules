def test_unparsable_ref_projection_pruned_by_stem_in_zcode(tmp_path):
    project = make_project(tmp_path)
    three_canon_rules(project)
    sync_rules.sync(str(project), target="zcode")
    # stale projection whose header reference is corrupted (unparsable) is
    # pruned by the canon-stem rule once the same-stem .mdc is gone —
    # exactly like the claude target
    proj = project / ".zcode" / "rules" / "db.md"
    proj.write_text(
        "<!-- generated by hermes context-rules from ??corrupted?? -->\n\nBody.\n")
    (project / ".cursor" / "rules" / "db.mdc").unlink()
    out = sync_rules.sync(str(project), target="zcode")
    assert not proj.exists()
    assert "removed: db.md" in out


